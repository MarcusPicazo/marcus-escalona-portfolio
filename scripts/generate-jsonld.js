#!/usr/bin/env node
/**
 * Regenerates the JSON-LD (Person + ItemList) and the <noscript> project
 * list in index.html from projectsData in main.js, so crawler-visible
 * content never drifts out of sync with the real data.
 *
 * Run after editing projectsData: `npm run generate:seo`.
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const mainJsPath = path.join(ROOT, "main.js");
const indexPath = path.join(ROOT, "index.html");

const mainJsSrc = fs.readFileSync(mainJsPath, "utf8");
const match = mainJsSrc.match(/const projectsData = (\[[\s\S]*?\n\]);/);
if (!match) {
  console.error("generate-jsonld: could not find `const projectsData = [...]` in main.js");
  process.exit(1);
}
const projectsData = new Function(`return ${match[1]};`)();

function stripHtml(html) {
  return html.replace(/<[^>]+>/g, " ").replace(/\s+/g, " ").trim();
}

function truncate(text, max) {
  if (text.length <= max) return text;
  const cut = text.slice(0, max);
  const lastSpace = cut.lastIndexOf(" ");
  return (lastSpace > 0 ? cut.slice(0, lastSpace) : cut) + "…";
}

function indentJson(obj, spaces) {
  const pad = " ".repeat(spaces);
  return JSON.stringify(obj, null, 2)
    .split("\n")
    .map((line) => pad + line)
    .join("\n");
}

const person = {
  "@context": "https://schema.org",
  "@type": "Person",
  name: "Marcus Escalona",
  jobTitle: "Senior Product Engineer",
  url: "https://marcusescalona.art",
  email: "mailto:marcuspicazo@outlook.com",
  sameAs: [
    "https://github.com/MarcusPicazo",
    "https://www.linkedin.com/in/marcus-escalona/",
  ],
  knowsLanguage: ["en", "es", "it", "ca"],
};

const itemList = {
  "@context": "https://schema.org",
  "@type": "ItemList",
  itemListElement: projectsData.map((proj, i) => ({
    "@type": "ListItem",
    position: i + 1,
    item: {
      "@type": "CreativeWork",
      name: proj.title.en,
      description: truncate(stripHtml(proj.desc.en), 160),
      url: proj.link,
    },
  })),
};

const jsonLdBlock = `    <!-- JSON-LD:START (auto-generated by scripts/generate-jsonld.js from projectsData in main.js. Do not hand-edit - edit main.js and run "npm run generate:seo" instead.) -->
    <script type="application/ld+json">
${indentJson(person, 6)}
    </script>
    <script type="application/ld+json">
${indentJson(itemList, 6)}
    </script>
    <!-- JSON-LD:END -->`;

const noscriptBlock = `  <!-- NOSCRIPT-PROJECTS:START (auto-generated by scripts/generate-jsonld.js from projectsData in main.js. Do not hand-edit.) -->
  <noscript>
    <ul>
${projectsData.map((p) => `      <li><a href="${p.link}">${p.title.en}</a></li>`).join("\n")}
    </ul>
  </noscript>
  <!-- NOSCRIPT-PROJECTS:END -->`;

let html = fs.readFileSync(indexPath, "utf8");

function replaceOrInsert(source, startMarker, endMarker, block, insertBeforeRegex) {
  const blockRe = new RegExp(`[ \\t]*${startMarker}[\\s\\S]*?${endMarker}\\n?`);
  if (blockRe.test(source)) {
    return source.replace(blockRe, block + "\n");
  }
  return source.replace(insertBeforeRegex, `${block}\n$&`);
}

html = replaceOrInsert(
  html,
  "<!-- JSON-LD:START",
  "<!-- JSON-LD:END -->",
  jsonLdBlock,
  /( *)<\/head>/
);
html = replaceOrInsert(
  html,
  "<!-- NOSCRIPT-PROJECTS:START",
  "<!-- NOSCRIPT-PROJECTS:END -->",
  noscriptBlock,
  /( *)<\/body>/
);

fs.writeFileSync(indexPath, html);
console.log(`generate-jsonld: wrote JSON-LD + noscript fallback for ${projectsData.length} projects into index.html`);
